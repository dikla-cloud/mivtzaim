const DEPT_WORDS_N = DEPT_WORDS.map(([d, keys]) => [d, keys.map(unfinal)]);
function autoDept(text) {
  const t = unfinal(String(text).split('|')[0].replace(/[׳"״]/g, (c) => (c === '״' || c === '"' ? '"' : "'")).toLowerCase().trim());
  const words = t.split(/\s+/).flatMap((w) => (/^[הובלמש]/.test(w) && w.length > 3 ? [w, w.slice(1)] : [w]));
  const has = (k) => (k[0] === '=' ? words.includes(k.slice(1)) : k.includes(' ') ? t.includes(k) : words.some((w) => w.startsWith(k)));
  for (const [dept, keys] of DEPT_WORDS_N) if (keys.some(has)) return dept;
  const icon = foodIcon(text);
  for (const [dept, icons] of Object.entries(DEPT_BY_ICON)) if (icons.includes(icon)) return dept;
  return 'other';
}
