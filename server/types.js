const N = TYPES.map((t) => ({
  keys: t.keys.map(normalize), exclude: (t.exclude || []).map(normalize), require: (t.require || []).map(normalize),
  subs: (t.subs || []).map((x) => ({ ...x, words: x.words.map(normalize) })),
}));

// הסוג שמתאים לחיפוש (השם בדיוק, או השם ועוד מילים – ״קפה טחון לוואצה״ ← קפה)
function typeOf(query) {
  const q = normalize(query);
  let best = null;
  for (const t of N) for (const k of t.keys) if ((q === k || q.startsWith(`${k} `)) && (!best || k.length > best.k.length)) best = { t, k };
  return best?.t || null;
}

// האם המוצר נשאר: לפי סוג המוצר שחיפשו
function allowed(type, query, name) {
  if (!type) return true;
  const q = ` ${normalize(query)} `;
  const n = ` ${normalize(name)} `;
  const words = n.trim().split(' ').flatMap((w) => (/^[הובלמש]/.test(w) && w.length > 2 ? [w, w.slice(1)] : [w]));
  const has = (k) => (k.includes(' ') ? n.includes(` ${k} `) || n.includes(` ${k}`) : words.some((w) => w.startsWith(k)));
  if (type.exclude.some((k) => !q.includes(` ${k}`) && has(k))) return false;
  if (type.require.length && !type.require.some(has)) return false;
  return true;
}

// מילה (תחילת מילה; עם רווח – צירוף) שמופיעה בשם המוצר
function nameHas(name, k) {
  const n = ` ${normalize(name)} `;
  const words = n.trim().split(' ').flatMap((w) => (/^[הובלמש]/.test(w) && w.length > 2 ? [w, w.slice(1)] : [w]));
  return k.includes(' ') ? n.includes(` ${k}`) : words.some((w) => w.startsWith(k));
}
const subMatches = (sub, name) => sub.words.some((k) => nameHas(name, k));

